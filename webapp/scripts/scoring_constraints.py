"""Write or check constraints-scoring.txt: the active manifest's frozen packages as pip constraints.

Ingestion refuses to score unless `pip freeze` in the scoring environment (.venv313) equals the list the active
candidate was frozen with (app/scoring/ingest_preflight.py, check_environment). requirements.txt pins only the
direct dependencies, so a plain `pip install -r requirements.txt` lets transitive ones float to newer releases
and the next ingest is refused. Installing with these constraints reproduces the frozen list exactly:

    .venv313\\Scripts\\python.exe -m pip install -r requirements.txt -c constraints-scoring.txt

Never install requirements-dev.txt (pytest-xdist) into .venv313: an extra package is refused too.

    python scripts/scoring_constraints.py write    # after a re-freeze changes ACTIVE_MANIFEST
    python scripts/scoring_constraints.py check    # exit 1 if the committed file is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

WEBAPP = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(WEBAPP))

CONSTRAINTS = WEBAPP / "constraints-scoring.txt"


def frozen_packages() -> tuple[str | None, list[str]]:
    """The active manifest's path and its recorded `pip freeze`; (None, []) when no manifest is active."""
    from app.scoring.impact_manifest import REPO_ROOT
    from app.scoring.impact_runtime import ACTIVE_MANIFEST

    if ACTIVE_MANIFEST is None:
        return None, []
    manifest = json.loads((REPO_ROOT / ACTIVE_MANIFEST).read_text(encoding="utf-8"))
    return ACTIVE_MANIFEST, list((manifest.get("environment") or {}).get("packages") or [])


def render() -> str:
    path, packages = frozen_packages()
    header = [
        "# Generated by scripts/scoring_constraints.py from the active scoring manifest -- do not edit by hand.",
        f"# Source: {path}" if path else "# No scoring manifest is active.",
        "# Build the scoring venv with: pip install -r requirements.txt -c constraints-scoring.txt",
    ]
    return "\n".join(header + packages) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("action", choices=["write", "check"])
    args = parser.parse_args(argv)
    expected = render()
    if args.action == "write":
        CONSTRAINTS.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {CONSTRAINTS.name}")
        return 0
    current = CONSTRAINTS.read_text(encoding="utf-8") if CONSTRAINTS.is_file() else ""
    if current.replace("\r\n", "\n") != expected:
        print(f"{CONSTRAINTS.name} does not match the active manifest; run: python scripts/scoring_constraints.py write")
        return 1
    print(f"{CONSTRAINTS.name} matches the active manifest")
    return 0


if __name__ == "__main__":
    sys.exit(main())
